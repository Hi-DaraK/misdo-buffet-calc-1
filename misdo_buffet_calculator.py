# サイドバーでカテゴリ選択
selected_category = st.sidebar.selectbox("カテゴリを選んでください：", category_list, index=0)

# フィルタリング
if selected_category == "すべて":
    view_df = df.copy()
else:
    view_df = df[df["カテゴリ"] == selected_category].copy()

# 入力エリア（同じキーで重複エラーが出ないよう商品名をキーに）
view_df["個数"] = view_df["商品名"].apply(
    lambda name: st.number_input(name, min_value=0, max_value=20, step=1, key=f"qty_{name}")
)

# 合計金額
total = int((view_df["価格"] * view_df["個数"]).sum())

